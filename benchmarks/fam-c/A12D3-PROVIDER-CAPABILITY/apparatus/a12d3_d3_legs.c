/*
 * Consume the single captured response from a SEALED memfd.
 *
 * D2 established that the handoff is a sealed memfd created with
 * memfd_create(MFD_ALLOW_SEALING) and sealed F_SEAL_WRITE|F_SEAL_GROW|
 * F_SEAL_SHRINK|F_SEAL_SEAL.  An on-disk copy is a labelled AUDIT COPY and is
 * NOT the handoff: F_ADD_SEALS is refused on ordinary files on this host
 * (EINVAL on ext4, EPERM on tmpfs), so a file cannot provide the same
 * guarantee.  D3 reuses that authority rather than inventing a second handoff.
 *
 * Returns 0 on success and writes the consumed length to *consumed.
 */
static int d3_consume_sealed_response(const char *env_name, size_t *consumed) {
    const char *fd_text = getenv(env_name);
    if (fd_text == NULL || fd_text[0] == '\0') {
        d3_note("SEALED_RESPONSE_ABSENT", "env=%s", env_name);
        return -1;
    }
    int fd = atoi(fd_text);
    if (fd < 0) return -1;

    /* Confirm the seals rather than assuming them: a descriptor that is merely
     * called "sealed" is not sealed. */
    int seals = fcntl(fd, F_GET_SEALS);
    if (seals < 0) {
        d3_note("SEALED_RESPONSE_UNSEALED", "env=%s errno=%d", env_name, errno);
        return -1;
    }
    const int required = F_SEAL_WRITE | F_SEAL_GROW | F_SEAL_SHRINK | F_SEAL_SEAL;
    if ((seals & required) != required) {
        d3_note("SEALED_RESPONSE_SEAL_MISMATCH", "observed=%d required=%d",
                seals, required);
        return -1;
    }

    struct stat st;
    if (fstat(fd, &st) != 0) return -1;
    off_t size = st.st_size;
    if (size <= 0) return -1;

    void *map = mmap(NULL, (size_t)size, PROT_READ, MAP_PRIVATE, fd, 0);
    if (map == MAP_FAILED) {
        d3_note("SEALED_RESPONSE_MAP_FAILED", "errno=%d", errno);
        return -1;
    }
    *consumed = (size_t)size;
    /* Touch the bytes so the mapping is genuinely consumed, not merely
     * established.  A mapping that is never read proves nothing. */
    volatile unsigned long acc = 0;
    const unsigned char *bytes = (const unsigned char *)map;
    for (off_t i = 0; i < size; i++) acc += bytes[i];
    (void)acc;
    munmap(map, (size_t)size);
    return 0;
}

/* ---- SHA-256 over consumed bytes.
 *
 * Signature and output convention match D2's leg implementation
 * (`sha256_hex(data, length, out)` writing 64 lowercase hex chars + NUL), so a
 * D3 receipt and a D2 receipt are directly comparable.  Self-contained because
 * the legs are built -Werror with no crypto library linked.
 */
typedef struct {
    uint32_t h[8];
    uint64_t length;
    unsigned char buffer[64];
    size_t buffered;
} d3_sha256_ctx;

static const uint32_t d3_sha256_k[64] = {
    0x428a2f98u, 0x71374491u, 0xb5c0fbcfu, 0xe9b5dba5u, 0x3956c25bu,
    0x59f111f1u, 0x923f82a4u, 0xab1c5ed5u, 0xd807aa98u, 0x12835b01u,
    0x243185beu, 0x550c7dc3u, 0x72be5d74u, 0x80deb1feu, 0x9bdc06a7u,
    0xc19bf174u, 0xe49b69c1u, 0xefbe4786u, 0x0fc19dc6u, 0x240ca1ccu,
    0x2de92c6fu, 0x4a7484aau, 0x5cb0a9dcu, 0x76f988dau, 0x983e5152u,
    0xa831c66du, 0xb00327c8u, 0xbf597fc7u, 0xc6e00bf3u, 0xd5a79147u,
    0x06ca6351u, 0x14292967u, 0x27b70a85u, 0x2e1b2138u, 0x4d2c6dfcu,
    0x53380d13u, 0x650a7354u, 0x766a0abbu, 0x81c2c92eu, 0x92722c85u,
    0xa2bfe8a1u, 0xa81a664bu, 0xc24b8b70u, 0xc76c51a3u, 0xd192e819u,
    0xd6990624u, 0xf40e3585u, 0x106aa070u, 0x19a4c116u, 0x1e376c08u,
    0x2748774cu, 0x34b0bcb5u, 0x391c0cb3u, 0x4ed8aa4au, 0x5b9cca4fu,
    0x682e6ff3u, 0x748f82eeu, 0x78a5636fu, 0x84c87814u, 0x8cc70208u,
    0x90befffau, 0xa4506cebu, 0xbef9a3f7u, 0xc67178f2u};

#define D3_ROTR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void d3_sha256_block(d3_sha256_ctx *ctx, const unsigned char *p) {
    uint32_t w[64];
    for (int i = 0; i < 16; i++) {
        w[i] = ((uint32_t)p[i * 4] << 24) | ((uint32_t)p[i * 4 + 1] << 16) |
               ((uint32_t)p[i * 4 + 2] << 8) | (uint32_t)p[i * 4 + 3];
    }
    for (int i = 16; i < 64; i++) {
        uint32_t s0 = D3_ROTR(w[i - 15], 7) ^ D3_ROTR(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = D3_ROTR(w[i - 2], 17) ^ D3_ROTR(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = ctx->h[0], b = ctx->h[1], c = ctx->h[2], d = ctx->h[3];
    uint32_t e = ctx->h[4], f = ctx->h[5], g = ctx->h[6], h = ctx->h[7];
    for (int i = 0; i < 64; i++) {
        uint32_t s1 = D3_ROTR(e, 6) ^ D3_ROTR(e, 11) ^ D3_ROTR(e, 25);
        uint32_t ch = (e & f) ^ ((~e) & g);
        uint32_t t1 = h + s1 + ch + d3_sha256_k[i] + w[i];
        uint32_t s0 = D3_ROTR(a, 2) ^ D3_ROTR(a, 13) ^ D3_ROTR(a, 22);
        uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = s0 + maj;
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }
    ctx->h[0] += a; ctx->h[1] += b; ctx->h[2] += c; ctx->h[3] += d;
    ctx->h[4] += e; ctx->h[5] += f; ctx->h[6] += g; ctx->h[7] += h;
}

static void d3_sha256_init(d3_sha256_ctx *ctx) {
    static const uint32_t iv[8] = {0x6a09e667u, 0xbb67ae85u, 0x3c6ef372u,
                                   0xa54ff53au, 0x510e527fu, 0x9b05688cu,
                                   0x1f83d9abu, 0x5be0cd19u};
    memcpy(ctx->h, iv, sizeof(iv));
    ctx->length = 0;
    ctx->buffered = 0;
}

static void d3_sha256_update(d3_sha256_ctx *ctx, const unsigned char *data,
                             size_t length) {
    ctx->length += length;
    while (length > 0) {
        size_t take = 64 - ctx->buffered;
        if (take > length) take = length;
        memcpy(ctx->buffer + ctx->buffered, data, take);
        ctx->buffered += take;
        data += take;
        length -= take;
        if (ctx->buffered == 64) {
            d3_sha256_block(ctx, ctx->buffer);
            ctx->buffered = 0;
        }
    }
}

/* Writes 64 lowercase hex characters plus a NUL. */
static void d3_sha256_hex(const unsigned char *data, size_t length, char *out) {
    d3_sha256_ctx ctx;
    d3_sha256_init(&ctx);
    d3_sha256_update(&ctx, data, length);
    uint64_t bits = ctx.length * 8u;
    unsigned char pad = 0x80;
    d3_sha256_update(&ctx, &pad, 1);
    unsigned char zero = 0x00;
    while (ctx.buffered != 56) d3_sha256_update(&ctx, &zero, 1);
    unsigned char tail[8];
    for (int i = 0; i < 8; i++) tail[i] = (unsigned char)(bits >> (56 - i * 8));
    d3_sha256_update(&ctx, tail, 8);
    static const char *hex = "0123456789abcdef";
    for (int i = 0; i < 8; i++) {
        for (int b = 0; b < 4; b++) {
            unsigned char byte = (unsigned char)(ctx.h[i] >> (24 - b * 8));
            *out++ = hex[byte >> 4];
            *out++ = hex[byte & 0x0f];
        }
    }
    *out = '\0';
}

/* ---- Consume the captured response BY PATH and publish point-of-use.
 *
 * systemd-run DROPS INHERITED DESCRIPTORS (measured twice in this apparatus),
 * so a live sealed memfd cannot be handed to this process: the payload sees
 * only fds 0/1/2.  The handoff is therefore the read-only audit copy on disk,
 * and this function re-establishes the IDENTITY the seal was protecting:
 *
 *   - it opens the copy O_RDONLY (a write attempt must fail),
 *   - it reads the base64 text and decodes it,
 *   - it SHA-256s the DECODED bytes it actually consumed,
 *   - it publishes that hash as point_of_use_sha256, the same field D2's legs
 *     publish, so the join to D2 evidence is by bytes and not by fd number.
 *
 * A leg that never read the bytes cannot produce this hash, and a leg that read
 * substituted bytes produces a different one.  That is what makes the join a
 * measurement instead of an assertion.
 */
static int d3_consume_sealed_by_path(size_t *consumed,
                                     char *out_sha, size_t out_sha_len,
                                     char *out_claim, size_t out_claim_len) {
    (void)out_sha_len;
    (void)out_claim_len;
    const char *path = getenv("D3_SEALED_RESPONSE_PATH");
    if (path == NULL || path[0] == '\0') {
        d3_note("SEALED_RESPONSE_ABSENT", "path_env=D3_SEALED_RESPONSE_PATH");
        return -1;
    }

    /* Read-only, and PROVE it: the handoff must refuse a write.  D2's guarantee
     * is the kernel seal (write -> EPERM); D3's path handoff carries the same
     * guarantee by making the copy unwritable, so the leg re-establishes the
     * observation instead of assuming it. */
    int fd = open(path, O_RDONLY);
    if (fd < 0) {
        d3_note("SEALED_RESPONSE_OPEN_FAILED", "errno=%d", errno);
        return -1;
    }
    errno = 0;
    int probe = open(path, O_WRONLY);
    if (probe >= 0) {
        close(probe);
        d3_note("SEALED_RESPONSE_HANDOFF_WRITABLE", "path=%s", path);
        close(fd);
        return -1;
    }
    int probe_errno = errno;
    if (probe_errno != EACCES && probe_errno != EROFS && probe_errno != EPERM) {
        d3_note("SEALED_RESPONSE_HANDOFF_PROBE_ERRNO", "errno=%d", probe_errno);
        close(fd);
        return -1;
    }

    struct stat st;
    if (fstat(fd, &st) != 0) { close(fd); return -1; }
    off_t size = st.st_size;
    if (size <= 0 || size > (off_t)(1 << 22)) { close(fd); return -1; }

    unsigned char *text = malloc((size_t)size + 1);
    if (text == NULL) { close(fd); return -1; }
    ssize_t got = read(fd, text, (size_t)size);
    close(fd);
    if (got != (ssize_t)size) { free(text); return -1; }
    text[size] = '\0';

    /* Decode base64 exactly as D2's legs do, so the hash is over the same
     * bytes the seal protected rather than over its transport encoding. */
    size_t decoded_cap = ((size_t)size / 4) * 3 + 4;
    unsigned char *decoded = malloc(decoded_cap);
    if (decoded == NULL) { free(text); return -1; }
    size_t decoded_size = 0;
    int quad[4]; int have = 0;
    for (off_t i = 0; i < size; i++) {
        unsigned char c = text[i];
        if (c == '=' ) { quad[have++] = -2; }
        else if (c >= 'A' && c <= 'Z') quad[have++] = c - 'A';
        else if (c >= 'a' && c <= 'z') quad[have++] = c - 'a' + 26;
        else if (c >= '0' && c <= '9') quad[have++] = c - '0' + 52;
        else if (c == '+') quad[have++] = 62;
        else if (c == '/') quad[have++] = 63;
        else continue;   /* whitespace and newlines are not payload */
        if (have == 4) {
            if (quad[0] >= 0 && quad[1] >= 0 && decoded_size < decoded_cap) {
                decoded[decoded_size++] = (unsigned char)((quad[0] << 2) | (quad[1] >> 4));
            }
            if (quad[2] >= 0 && decoded_size < decoded_cap) {
                decoded[decoded_size++] = (unsigned char)(((quad[1] & 0xF) << 4) | (quad[2] >> 2));
            }
            if (quad[3] >= 0 && decoded_size < decoded_cap) {
                decoded[decoded_size++] = (unsigned char)(((quad[2] & 0x3) << 6) | quad[3]);
            }
            have = 0;
        }
    }
    free(text);

    /* SHA-256 over the bytes ACTUALLY CONSUMED. */
    char digest[65];
    d3_sha256_hex(decoded, decoded_size, digest);
    memcpy(out_sha, digest, 65);
    memcpy(out_claim, digest, 65);
    *consumed = decoded_size;

    /* Touch every byte so the consumption is real, not a hash of a struct. */
    volatile unsigned long acc = 0;
    for (size_t i = 0; i < decoded_size; i++) acc += decoded[i];
    (void)acc;
    free(decoded);
    return 0;
}

