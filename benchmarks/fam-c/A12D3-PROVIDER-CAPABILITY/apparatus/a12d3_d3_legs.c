/* The entry barrier                                                   */
/* ------------------------------------------------------------------ */

/*
 * Reach the entry barrier and BLOCK until the inspector releases us.
 *
 * PRECONDITION: the denial policy is already installed.  This function is only
 * ever called after a successful d3_install_denial_policy(), so the process is
 * filtered at the instant it becomes externally measurable.  That is the whole
 * point: the measurement, the activation evidence, and the allowlist
 * reconciliation all happen while this process sits inside the pause() below,
 * and the process is ALREADY FILTERED for that entire window.
 *
 * THE RENDEZVOUS HOLDS NO FILE DESCRIPTOR, DELIBERATELY.
 *
 * An earlier revision blocked in open(FIFO, O_RDONLY).  That works, but it
 * means the leg acquires a descriptor AFTER the filter is installed and then
 * holds it ACROSS the measurement window -- so the measured descriptor set
 * depends on when the measurement is taken relative to that acquisition, and
 * the allowlist needs a timing caveat to explain away a descriptor that is
 * genuinely present.  A timing caveat is exactly the kind of seam through which
 * a real capability could hide: it teaches the reader to accept "this
 * descriptor is present but that is fine here".
 *
 * Blocking in pause() removes the seam instead of documenting it.  The leg
 * touches no descriptor between installing the filter and being measured, so
 * the measured non-stdio set is exactly the set that was inherited, with no
 * caveat and no phase-dependence.  Release is a signal from the harness to this
 * (already externally VERIFIED) pid -- delivered into the kernel's signal
 * machinery, carrying no data and requiring no descriptor on either side.
 *
 * The hold is externally observable.  Measured on this host (kernel
 * 7.0.0-31-generic): /proc/<pid>/status reads "State: S (sleeping)" and
 * /proc/<pid>/wchan reads "sigsuspend".  Neither can be produced by a process
 * that is actually running, and the inspector reads both from OUTSIDE the leg,
 * so the hold is evidence rather than assertion.  (An earlier draft of this
 * comment predicted wchan "do_signal_pause"; the measured symbol is
 * "sigsuspend".  The prediction was wrong, and the measurement is what counts.)
 */
static volatile sig_atomic_t d3_barrier_signal_seen = 0;

static void d3_barrier_handler(int signo) {
    (void)signo;
    d3_barrier_signal_seen = 1;
}

static int d3_await_entry_barrier(void) {
    /* Signals must arrive BEFORE we block, or a harness that releases us
     * promptly would deliver into the default disposition and kill us.  Install
     * the handler first, and mask SIGUSR1 across the pause so the wakeup cannot
     * be lost in the window between the readiness note and the pause itself. */
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = d3_barrier_handler;
    sigemptyset(&sa.sa_mask);
    sa.sa_flags = 0;                 /* NO SA_RESTART: pause() must return */
    if (sigaction(SIGUSR1, &sa, NULL) != 0) {
        d3_note("ENTRY_BARRIER_FAILED", "sigaction_errno=%d", errno);
        return -1;
    }

    sigset_t block, previous;
    sigemptyset(&block);
    sigaddset(&block, SIGUSR1);
    if (sigprocmask(SIG_BLOCK, &block, &previous) != 0) {
        d3_note("ENTRY_BARRIER_FAILED", "sigprocmask_errno=%d", errno);
        return -1;
    }

    /* Announce AFTER the handler and mask are in place, so the harness can
     * never send into an unprepared process.  This marker is the point from
     * which a release signal is safe, and the inspector treats it as the start
     * of the hold window. */
    d3_note("ENTRY_BARRIER_REACHING", "rendezvous=signal mode=no_held_fd");

    /* Unmask-and-sleep atomically.  sigsuspend() cannot miss a signal that
     * arrives in the gap the way an unmask-then-pause pair can. */
    while (!d3_barrier_signal_seen) {
        if (sigsuspend(&previous) != 0 && errno != EINTR) {
            d3_note("ENTRY_BARRIER_FAILED", "sigsuspend_errno=%d", errno);
            return -1;
        }
    }

    /* Restore the caller's mask; the barrier is over. */
    sigprocmask(SIG_SETMASK, &previous, NULL);
    d3_note("BUSINESS_LOGIC_RELEASED", "barrier_released=1 rendezvous=signal");
    return 0;
}

