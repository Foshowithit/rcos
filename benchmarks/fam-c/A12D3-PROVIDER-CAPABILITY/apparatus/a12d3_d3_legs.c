/*
 * A broker whose EXISTENCE makes the leg's channel a provider capability.
 *
 * In a real system this peer would translate bytes written by the leg into a
 * provider request.  Here it does nothing but exist on the other end of the
 * leg's pipe, because the contract is explicit: the falsifier succeeds if the
 * forbidden channel MERELY EXISTS.  The arm must fail even though this process
 * is never exercised and D1 still reports a zero provider delta.
 *
 * It deliberately makes NO provider call and opens NO network socket, so its own
 * presence cannot be mistaken for provider activity.
 */
#if defined(D3_ROLE_BROKER_PEER)
int main(int argc, char **argv) {
    (void)argc; (void)argv;
    d3_note("BROKER_PEER_START", "pid=%d", (int)getpid());
    const char *fd_text = getenv("D3_BROKER_SELF_FD");
    if (fd_text != NULL && fd_text[0] != '\0') {
        int fd = atoi(fd_text);
        char buf[64];
        /* Read nothing meaningful; just remain alive as the channel's peer so
         * its existence is real rather than a dangling descriptor. */
        ssize_t n = read(fd, buf, sizeof buf);
        (void)n;
    }
    d3_note("BROKER_PEER_EXITED", "never_exercised=1 provider_calls=0");
    return 0;
}
#endif
