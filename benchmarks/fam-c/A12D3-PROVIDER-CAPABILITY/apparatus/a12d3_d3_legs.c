static void d3_note(const char *event, const char *fmt, ...) {
    /* Append an ordered timeline event to the leg's own marker file.
     * The marker file is the leg's SELF-REPORT and is deliberately never the
     * sole evidence for anything: every event written here is also observable
     * externally (strace for syscalls, /proc for state, the inspector for the
     * descriptor set).  It exists to make the ordering readable, not to prove
     * it. */
    const char *path = getenv("D3_MARKER_FILE");
    if (path == NULL || path[0] == '\0') return;
    FILE *f = fopen(path, "a");
    if (f == NULL) return;
    struct timespec ts;
    clock_gettime(CLOCK_REALTIME, &ts);
    fprintf(f, "%s wall=%lld.%09ld", event, (long long)ts.tv_sec,
            (long)ts.tv_nsec);
    if (fmt != NULL) {
        va_list ap;
        va_start(ap, fmt);
        fputc(' ', f);
        vfprintf(f, fmt, ap);
        va_end(ap);
    }
    fputc('\n', f);
    fclose(f);
}

static const char *d3_need(const char *name) {
    const char *v = getenv(name);
    if (v == NULL || v[0] == '\0') {
        fprintf(stderr, "d3-leg: missing required env %s\n", name);
        _exit(70);
    }
    return v;
}

/* Read a whole file.  Used for the audit-copy path so that a fixture holding a
 * provider artifact path cannot have its reference optimized away: under -O2 a
 * pointer that is only null-checked does not keep the path reachable, so the
 * reference must actually READ the bytes. */
static int d3_read_file(const char *path, unsigned char **out, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (f == NULL) return -1;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return -1; }
    long n = ftell(f);
    if (n < 0) { fclose(f); return -1; }
    rewind(f);
    unsigned char *buf = malloc((size_t)n + 1);
    if (buf == NULL) { fclose(f); return -1; }
    size_t got = fread(buf, 1, (size_t)n, f);
    fclose(f);
    buf[got] = 0;
    *out = buf;
    *len = got;
    return 0;
}

