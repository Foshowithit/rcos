/* Whether this leg is the arm's OFFENDING leg.  Emission and intent both hang
 * off this, never off the identity: an honest leg in a negative arm must behave
 * exactly like an honest leg in the clean arm, or the arm would compare two
 * different things. */
#define D3_LEG_IS_OFFENDER (D3_LEG_INJECTION != D3_INJECT_NONE)
/* A leg that holds an actual capability (as opposed to merely attempting to
 * create one) can be checked for possession. */
#define D3_LEG_HAS_ANY_POSSESSED_CAPABILITY \
    (D3_LEG_INJECTION == D3_INJECT_INHERITED_PROVIDER_SOCKET || \
     D3_LEG_INJECTION == D3_INJECT_BROKER_CHANNEL)
#define D3_LEG_ATTEMPTS_DENIED_OPS (D3_LEG_IS_OFFENDER)

/* Write the D2-compatible per-leg receipt.  Field names match D2's leg
 * receipts so an auditor can diff D3 against D2 directly. */
static int d3_write_leg_receipt(const char *role, const char *sha,
                                size_t consumed) {
    const char *dir = getenv("D3_RECEIPT_DIR");
    if (dir == NULL || dir[0] == '\0') return -1;
    char path[1024];
    snprintf(path, sizeof(path), "%s/%s.receipt.json", dir, role);
    int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    if (fd < 0) return -1;
    /* build_identity / build_injection are the TWO COMPILE-TIME AXES this
     * binary was built with.  They are emitted so the axes are structurally
     * observable from an artifact instead of being inferred from the binary --
     * an inference that silently fails whenever the compiler folds a short
     * string literal, which is exactly what happened to "ON": `strings` could
     * not see it, so a check built on `strings` reported a missing identity for
     * a binary that was in fact built correctly.  A receipt field the leg
     * itself writes cannot be optimized away. */
    dprintf(fd,
            "{\"leg\":\"%s\",\"point_of_use_sha256\":\"%s\","
            "\"claimed_metadata_sha256\":\"%s\",\"bytes_consumed\":%zu,"
            "\"proof\":\"decoded_actual_consumed_bytes\",\"provider_calls\":0,"
            "\"sealed_handoff\":\"read_only_path_copy_not_fd\","
            "\"response_source\":\"delegated_readonly_descriptor_family\","
            "\"build_identity\":\"%s\",\"build_injection\":\"%s\","
            "\"build_is_offender\":%s}\n",
            role, sha, sha, consumed, D3_LEG_ROLE, D3_LEG_INJECTION_NAME,
            D3_LEG_IS_OFFENDER ? "true" : "false");
    close(fd);
    return 0;
}

