/*
 * A12D3 / D3 counterfactual leg stand-ins  --  NATIVE C, TEST-ONLY.
 *
 * THIS FILE IS NOT A13 CODE AND AWARDS NO ELIGIBILITY.
 *
 * WHAT CHANGED FROM D2
 * --------------------
 * D2's legs asked "how much cognition did this leg create, and could it reach a
 * provider artifact statically".  D3 asks a different and stronger question:
 * DID THE LEG POSSESS A USABLE PROVIDER-COGNITION CAPABILITY.  A leg can create
 * zero cognition and still hold a live socket to a provider-capable endpoint; it
 * can contain zero provider markers and still inherit a channel that would
 * translate its bytes.  So D3's legs must be measurable at a moment when they
 * are (a) filtered and (b) provably not yet running business logic, and their
 * descriptor set at that moment must be inspectable from OUTSIDE.
 *
 * THE MANDATED IN-LEG ORDER (load-bearing; a violation is a capability window)
 * --------------------------------------------------------------------------
 *     LEG_PROCESS_START
 *     DENIAL_POLICY_INSTALLED          <- seccomp filter attached
 *     ENTRY_BARRIER_REACHED            <- blocked in read() on a barrier FIFO
 *     DESCRIPTOR_SET_MEASURED_EXTERNALLY   (by the inspector, while we block)
 *     POLICY_ACTIVATION_EVIDENCED          (kernel's own /proc/<pid>/status)
 *     DESCRIPTOR_ALLOWLIST_RECONCILED      (inspector, while we block)
 *     BUSINESS_LOGIC_RELEASED          <- barrier released, only NOW do work
 *
 * The FORBIDDEN order is:  measure clean FDs -> release -> install seccomp.
 * That order leaves a window in which the leg has an unfiltered capability set.
 * The code below makes the forbidden order UNREPRESENTABLE rather than merely
 * avoided: there is no branch, flag, or argument that reaches the barrier
 * without first passing through the installer, because the barrier read is the
 * last statement of a function that opens with the install and returns early on
 * any installation failure.
 *
 * WHY THE BARRIER IS A FIFO AND NOT A SLEEP
 * -----------------------------------------
 * open(O_RDONLY) on a FIFO with no writer BLOCKS IN THE KERNEL until a writer
 * appears.  The inspector's open(O_WRONLY) is therefore the release, and the
 * hold is a kernel rendezvous rather than a timing assumption.  A sleep would
 * be evidence that the leg *chose* to wait; this is evidence that it *cannot*
 * proceed.  The inspector additionally confirms the blocked state externally
 * via /proc/<pid>/status State and /proc/<pid>/wchan.
 *
 * ROLE SELECTION
 * --------------
 * One translation unit, one role per build, selected by -D macros from the
 * per-role header.  The point-of-use code is therefore the SAME OBJECT CODE in
 * every arm, so a divergence in consumed bytes is a divergence in BYTES, never
 * a divergence in code.  This is what lets a negative arm fail on its own
 * capability rather than on an accidentally different code path.
 */

