/*
 * Attempt the ops the frozen conjuncts name, and record what the KERNEL said.
 *
 * These run AFTER the barrier release, i.e. after the policy was installed and
 * independently evidenced.  That ordering is what makes the witness
 * "..._DENIED_AFTER_LEG_ENTRY" provable: the denials are attributable to a
 * policy whose activation was evidenced while the leg was still held, and the
 * strace timestamps place them after the barrier.
 *
 * A process CAN install a second seccomp filter, and PR_SET_NO_NEW_PRIVS is
 * idempotent, so doing this inside the already-filtered leg is well defined.
 * This is preferred over a separate uninstrumented helper because every denial
 * witness then sits under the same precommitted policy hash.
 *
 * Each attempt is recorded with its errno so the classifier can require a
 * RETURNED errno (EACCES=13 or EPERM=1) and reject anything else -- especially a
 * kill, which would mean the filter used a killing action.
 *
 * WHY EVERY ARM PROBES.  The conjuncts NETWORK/PROCESS/EXEC_DENIED_AFTER_LEG_ENTRY
 * are properties of the ENTRY BOUNDARY, not of any one arm: they assert that a
 * process standing past the barrier cannot create a network socket, a process,
 * or an execution.  Proving that requires asking, so every arm asks -- including
 * the clean one, whose refusal is what shows the denial is a property of the
 * policy rather than of the arm's role.  The arms still differ, but in what they
 * POSSESS, never in whether they probe: a possession arm that also probed would
 * conflate "held a capability" with "tried to use one" and could not be
 * attributed to either.
 *
 * The two things stay separable because the ATTEMPT failure code is derived
 * from whether the probe was DENIED, not from whether it was made.
 */
static void d3_attempt_denied_ops(void) {
    int rc;
    int err;

    /* Whether this arm is the KIND of arm that tries to reach provider
     * cognition.  This is an EMISSION switch, not a behaviour switch: the probe
     * below runs in every arm so the three *_DENIED_AFTER_LEG_ENTRY conjuncts
     * are demonstrable everywhere.  What differs is the arm's INTENT, which is
     * what the ATTEMPT failure code is about.
     *
     * Stated plainly: an arm that holds no capability and would not use one is
     * not "attempting provider cognition" merely because the harness asked it to
     * probe the policy.  D3-C (direct network attempt) and D3-D (fork/exec
     * escape) are the arms whose PURPOSE is to try; the others probe only to
     * evidence the boundary. */
#if D3_LEG_ATTEMPTS_DENIED_OPS
    d3_note("ATTEMPT_INTENT", "role=%s intent=reach_provider_cognition",
            D3_LEG_ROLE);
#else
    d3_note("ATTEMPT_INTENT", "role=%s intent=none", D3_LEG_ROLE);
#endif

    /* 1. NETWORK_CREATION_DENIED_AFTER_LEG_ENTRY */
    errno = 0;
    rc = socket(AF_INET, SOCK_STREAM, 0);
    err = errno;
    d3_note("ATTEMPT_NETWORK_CREATION", "socket_rc=%d errno=%d", rc, err);
    if (rc >= 0) close(rc);

    errno = 0;
    int pair[2] = { -1, -1 };
    rc = socketpair(AF_UNIX, SOCK_STREAM, 0, pair);
    err = errno;
    d3_note("ATTEMPT_NETWORK_CREATION", "socketpair_rc=%d errno=%d", rc, err);
    if (rc == 0) { close(pair[0]); close(pair[1]); }

    /* 2. PROCESS_CREATION_DENIED_AFTER_LEG_ENTRY */
    errno = 0;
    pid_t child = fork();
    err = errno;
    d3_note("ATTEMPT_PROCESS_CREATION", "fork_rc=%d errno=%d", (int)child, err);
    if (child > 0) {
        int status = 0;
        /* Only reached if fork unexpectedly succeeded; reap so a stray child
         * cannot keep the cgroup non-quiescent. */
        waitpid(child, &status, 0);
    }

    /* 3. EXEC_DENIED_AFTER_LEG_ENTRY.
     * Non-destructive: the denied execve returns EACCES and this process keeps
     * running, so the leg can still finish honestly.  The argument vector is
     * real because -Werror rejects execve(..., NULL, NULL) as nonnull. */
    errno = 0;
    char *const exec_argv[] = { (char *)"true", NULL };
    execve("/bin/true", exec_argv, NULL);
    err = errno;   /* only reached because the exec was DENIED */
    d3_note("ATTEMPT_EXEC", "execve_rc=-1 errno=%d exec_denied=1", err);
}

/*
 * Acquire the capabilities this arm is built to POSSESS.
 *
 * This runs BEFORE the denial policy is installed, so it is the only window in
 * which the fixture may create a descriptor at all.  Each arm's block is
 * compiled in or out by its role header, so a clean arm executes none of this
 * and a negative arm executes exactly one branch -- the arms differ by which
 * capability they possess, never by control flow.
 *
 * Every acquisition VERIFIES what it acquired with fstat().  A handoff that
 * silently delivers nothing is worse than a crash: it yields an arm that
 * appears to test inheritance while holding nothing, which is precisely the
 * failure this harness exists to detect in others and must not commit itself.
 */
static int d3_acquire_possessed_capabilities(void) {
#if !D3_LEG_HAS_ANY_POSSESSED_CAPABILITY
    /* Clean arm: nothing to acquire.  The statements below are compiled out
     * rather than skipped at runtime, so a clean arm cannot be argued to have
     * taken a branch that would have acquired something. */
    return 0;
#else
#if D3_LEG_INJECTION == D3_INJECT_INHERITED_PROVIDER_SOCKET
    {
        /* An ALREADY-CONNECTED provider-capable socket.  The arm must fail on
         * the mere POSSESSION of this descriptor even if nothing is ever
         * written.
         *
         * WHY CONNECT RATHER THAN RECEIVE AN FD.  The faithful model of
         * inheritance is "the leg holds a descriptor it did not create", and
         * the launcher cannot deliver one: systemd-run does not preserve
         * inherited descriptors (measured: a payload sees only 0/1/2 plus its
         * own /proc/self/fd handle).  Handing the leg an fd number therefore
         * produced an arm that CLAIMED a capability while holding nothing, and
         * the external measurement correctly disagreed with it.
         *
         * So the leg RECONNECTS to the fixture's already-listening provider
         * endpoint, before the denial policy is installed.  This is the same
         * object D2 treats as a captured-response boundary: the endpoint is
         * precommitted by path, the fixture owns it, and the leg's only act is
         * to durably hold the resulting channel.  The descriptor that survives
         * into the measured window is one the leg never creates under the
         * policy -- the policy forbids socket() outright, so this could not be
         * done afterwards even if the code tried.
         *
         * POSSESSION IS VERIFIED, NOT ASSUMED.  fstat() asks the kernel whether
         * the descriptor denotes an open file; a claimed-but-absent capability
         * is a LOUD FAILURE, never a quiet pass. */
        const char *path = getenv("D3_PROVIDER_ENDPOINT_PATH");
        int inherited = -1;
        if (path != NULL && path[0] != '\0') {
            int probe = socket(AF_UNIX, SOCK_STREAM, 0);
            if (probe >= 0) {
                struct sockaddr_un addr;
                memset(&addr, 0, sizeof(addr));
                addr.sun_family = AF_UNIX;
                snprintf(addr.sun_path, sizeof(addr.sun_path), "%s", path);
                if (connect(probe, (struct sockaddr *)&addr,
                            sizeof(addr)) == 0) {
                    inherited = probe;
                } else {
                    close(probe);
                }
            }
        }
        struct stat inherited_stat;
        int have_inherited = (inherited >= 0 &&
                              fstat(inherited, &inherited_stat) == 0);
        d3_note("CAPABILITY_ACQUIRED", "kind=inherited_provider_socket fd=%d "
                "verified=%d errno=%d", inherited, have_inherited,
                have_inherited ? 0 : errno);
        if (!have_inherited) {
            d3_note("CAPABILITY_HANDOFF_FAILED",
                    "kind=inherited_provider_socket fd=%d errno=%d", inherited,
                    errno);
            return D3_EXIT_CAPABILITY_HANDOFF_FAILED;
        }
        /* Deliberately do NOT use it: D3-B's whole point is that possession
         * suffices, so nothing is ever written to this channel. */
    }
#endif

#if D3_LEG_INJECTION == D3_INJECT_BROKER_CHANNEL
    {
        /* A channel whose PEER is a broker that would translate our bytes into
         * a provider request.  The descriptor looks innocent -- a pipe carries
         * no provider identity -- so the allowlist alone would pass it.  It is
         * the PEER that makes it a capability, and the arm must fail on the
         * channel's EXISTENCE without exercising it.
         *
         * As in D3-B the leg RECONNECTS rather than receiving an fd, for the
         * same measured reason (the launcher drops inherited descriptors).
         * Possession is verified with fstat() so a claimed-but-absent channel
         * fails loudly instead of quietly producing an arm that proves
         * nothing. */
        const char *path = getenv("D3_BROKER_ENDPOINT_PATH");
        int peer_fd = -1;
        if (path != NULL && path[0] != '\0') {
            int probe = socket(AF_UNIX, SOCK_STREAM, 0);
            if (probe >= 0) {
                struct sockaddr_un addr;
                memset(&addr, 0, sizeof(addr));
                addr.sun_family = AF_UNIX;
                snprintf(addr.sun_path, sizeof(addr.sun_path), "%s", path);
                if (connect(probe, (struct sockaddr *)&addr,
                            sizeof(addr)) == 0) {
                    peer_fd = probe;
                } else {
                    close(probe);
                }
            }
        }
        struct stat peer_stat;
        int have_peer = (peer_fd >= 0 && fstat(peer_fd, &peer_stat) == 0);
        d3_note("CAPABILITY_ACQUIRED", "kind=broker_channel fd=%d verified=%d "
                "errno=%d", peer_fd, have_peer, have_peer ? 0 : errno);
        if (!have_peer) {
            d3_note("CAPABILITY_HANDOFF_FAILED", "kind=broker_channel fd=%d "
                    "errno=%d", peer_fd, errno);
            return D3_EXIT_CAPABILITY_HANDOFF_FAILED;
        }
        /* Never written to: existence alone is the violation. */
    }
#endif

    return 0;
#endif
}

static int d3_run_leg(void) {
    if (strcmp(d3_need("D3_LEG_ROLE"), D3_LEG_ROLE) != 0) return 90;

    d3_note("LEG_PROCESS_START", "pid=%d role=%s", (int)getpid(), D3_LEG_ROLE);

    /* ---- CAPABILITY POSSESSION, BEFORE THE POLICY INSTALL ----
     *
     * Order matters and is not stylistic.  The capability must be in hand
     * before the denial policy goes on, for two independent reasons:
     *
     *  1. It is the ONLY faithful model of a real inheritance.  A leg that
     *     acquires a provider socket after the filter is installed has done so
     *     under the policy -- and the policy denies socket(), so it could not
     *     have done it at all.  Real inheritance happens before the leg has any
     *     say, which is exactly why it is dangerous.
     *  2. The inspector measures the descriptor set AT THE ENTRY BARRIER.  Any
     *     acquisition placed after the barrier is invisible to that
     *     measurement, so an arm could hold a provider capability and still be
     *     reconciled as clean.  That is a hole in the evidence, not a detail.
     */
    if (d3_acquire_possessed_capabilities() != 0) {
        return D3_EXIT_CAPABILITY_HANDOFF_FAILED;
    }

    /* ---- The mandatory order begins. ---- */

    /* (1) Install the denial policy BEFORE anything is measurable. */
    if (d3_install_denial_policy() != 0) return 71;
    int in_process_mode = d3_confirm_policy_in_process();
    d3_note("DENIAL_POLICY_INSTALLED", "pr_get_seccomp=%d filter_sha256=%s",
            in_process_mode, D3_DENIAL_FILTER_SHA256);

    /* (2) Reach the barrier and block.  Everything the inspector does happens
     *     inside this call, against an ALREADY-FILTERED process.
     *
     *     The barrier is a rendezvous with the ARM'S tracer, which releases the
     *     leg once it has finished inspecting it.  A leg spawned by the model
     *     CELL has no tracer waiting on it, so it would block here forever and
     *     hang the cell.  That is not a relaxation of the boundary: the cell's
     *     leg is a control artifact the cell counts, not a measured leg, and the
     *     arm's own measured legs still take the barrier unconditionally.  The
     *     skip is granted only through an env var the CELL sets on its child, so
     *     no measured leg can reach this branch. */
    const char *cell_child = getenv("D3_CELL_CHILD_NO_BARRIER");
    if (cell_child && strcmp(cell_child, "1") == 0) {
        d3_note("ENTRY_BARRIER_SKIPPED", "reason=cell_child_no_tracer");
    } else if (d3_await_entry_barrier() != 0) {
        return 72;
    }

    /* ---- Only now does business logic exist. ---- */

    /* (3) Optional fixture-acquired capability.  D3_LEG_HAS_* is the single
     *     build-time knob; the acquire is a no-op in clean arms, so the
     *     clean and negative arms run the same statements. */
    /* (4) Consume the single captured response.  EVERY arm consumes it, so
     *     HONEST_COUNTERFACTUAL_LEGS_COMPLETE has content: a leg that never read
     *     the response cannot claim honest completion. */
    size_t consumed = 0;
    char point_of_use[65] = {0};
    char claim[65] = {0};
    if (d3_consume_sealed_by_path(&consumed, point_of_use, sizeof(point_of_use),
                                  claim, sizeof(claim)) == 0) {
        d3_note("SEALED_RESPONSE_CONSUMED",
                "bytes=%zu point_of_use_sha256=%.16s...", consumed, point_of_use);
        if (d3_write_leg_receipt(D3_LEG_ROLE, point_of_use, consumed) == 0) {
            d3_note("LEG_RECEIPT_WRITTEN", "role=%s bytes=%zu",
                    D3_LEG_ROLE, consumed);
        } else {
            d3_note("LEG_RECEIPT_WRITE_FAILED", "role=%s", D3_LEG_ROLE);
        }
    } else {
        d3_note("SEALED_RESPONSE_NOT_CONSUMED", "bytes=0");
    }

    /* (5) Attempt the denied operations and record the kernel's answer. */
    d3_attempt_denied_ops();

    d3_note("LEG_COMPLETED", "role=%s consumed=%zu", D3_LEG_ROLE, consumed);
    return 0;
}
