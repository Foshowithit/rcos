/*
 * The counterfactual leg.  Identical object code in every arm; the ONLY
 * build-time difference is the role header it is compiled against, which
 * selects which capabilities the fixture acquires.  A negative arm therefore
 * fails on the capability it holds, not on a different code path.
 *
 * The role header is included ONLY for the leg role.  Model-cell, order-cell,
 * and broker-peer builds are not passed D3_LEG_ROLE_HEADER at all, so an
 * unguarded include here would break their compiles -- and, worse, would invite
 * "fixing" it by giving every role a dummy header, which would let a role build
 * silently acquire a capability switch it was never meant to have.
 */

/*
 * =====================================================================
 * TWO INDEPENDENT AXES: which D2 leg this is, and what it was injected with
 * =====================================================================
 *
 * The role header defines TWO things that must not be conflated:
 *
 *   D3_LEG_ROLE            -- the leg's IDENTITY.  Always one of D2's three
 *                             legs: "ON", "OFF_NOOP", "ADAPTER_ONLY_PASS_THROUGH".
 *                             This is the name it writes its receipt under, and
 *                             the name the D2 identity join matches on.
 *   D3_LEG_INJECTION       -- the OFFENDING capability or behaviour planted in
 *                             this leg, or D3_INJECT_NONE.  At most ONE leg per
 *                             arm carries a non-NONE injection; the other two
 *                             are honest and must complete normally under the
 *                             SAME policy hash.
 *
 * WHY THE SPLIT IS REQUIRED.  With one leg per arm, an arm that failed proved
 * only that the harness could stop the counterfactual executable -- the honest
 * legs never ran in the same arm, so nothing showed the boundary distinguishes a
 * possessed capability from an ordinary leg.  With three legs per arm and the
 * injection confined to one, an arm that fails while its two honest siblings
 * complete under the identical policy is evidence about the BOUNDARY.
 *
 * The identity axis is D2's; D3 adds no new leg vocabulary.  The injection axis
 * is D3's, and it is the only thing that differs between arms.
 */



