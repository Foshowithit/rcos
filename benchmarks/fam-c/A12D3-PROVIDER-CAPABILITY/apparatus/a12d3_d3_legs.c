/*
 * Install the precommitted seccomp filter.
 *
 * Ordering matters and is fixed here:
 *   1. PR_SET_NO_NEW_PRIVS  -- required or the kernel refuses the filter.
 *   2. seccomp(2) with SECCOMP_FILTER_FLAG_LOG -- the filter itself, AND the
 *      kernel-side audit record for every denial it returns.
 *
 * Step 2 uses the seccomp(2) SYSCALL, not prctl(PR_SET_SECCOMP, ...).  See the
 * comment at the install site: prctl cannot carry the LOG flag, and without it
 * a denial is witnessed only by the denying process's own marker.
 *
 * The filter RETURNS EACCES; it never kills.  That is deliberate: D3-A's clean
 * legs must COMPLETE HONESTLY under the very same policy, so a killing filter
 * would make honest completion impossible and would destroy the arm that proves
 * the policy is not simply breaking everything.  A SIGSYS/kill observed in
 * strace is therefore recorded as a policy defect, never accepted as evidence.
 *
 * The arch guard inside the filter (emitted first) returns ALLOW for any
 * seccomp_data.arch != AUDIT_ARCH_X86_64 so a foreign-ABI number space cannot
 * be used to escape the deny table.
 */
static int d3_install_denial_policy(void) {
    struct sock_fprog prog;
    prog.len = (unsigned short)D3_DENIAL_INSTRUCTION_COUNT;
    prog.filter = (struct sock_filter *)(void *)d3_denial_filter_program;

    if (prctl(PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0) {
        d3_note("DENIAL_POLICY_INSTALL_FAILED", "stage=no_new_privs errno=%d",
                errno);
        return -1;
    }
    /*
     * Install through the seccomp(2) SYSCALL, not prctl(PR_SET_SECCOMP, ...).
     *
     * PR_SET_SECCOMP IGNORES prctl's 4th and 5th arguments: prctl always reaches
     * the kernel's seccomp_set_mode_filter() with flags = 0.  SECCOMP_FILTER_FLAG_LOG
     * therefore CANNOT be set through prctl, and without that flag the kernel
     * writes no `type=1326` audit record for a denial.
     *
     * Measured consequence (2026-09-11): the battery ran green while the journal
     * held ZERO `type=1326` records for its window, leaving every denial witnessed
     * only by the leg's OWN self-reported errno=13 marker -- the class of evidence
     * this contract says must not carry the argument alone.
     *
     * With the flag honoured the same run emits one record per denied attempt
     * (`sig=0 ... code=0x50000`, i.e. SECCOMP_RET_ERRNO returned, not a kill).
     * Filter BYTES are unchanged: deny set, errno and ALLOW default are identical;
     * only whether the kernel ALSO logs changes.
     */
    if (syscall(SYS_seccomp, SECCOMP_SET_MODE_FILTER,
                (unsigned int)SECCOMP_FILTER_FLAG_LOG, &prog) != 0) {
        d3_note("DENIAL_POLICY_INSTALL_FAILED", "stage=set_seccomp errno=%d",
                errno);
        return -1;
    }
    return 0;
}

/*
 * Verify the policy is active IN-PROCESS, and report agreement with the
 * externally read value.
 *
 * PR_GET_SECCOMP is read in a SEPARATE statement from the installer on purpose:
 * putting the install and the read in one expression leaves the evaluation order
 * unspecified and can read the state BEFORE the install, which silently reports
 * 0 for a filtered process.  That bug was hit and fixed during development; the
 * separation is the fix, not a style choice.
 *
 * This in-process value is CORROBORATION ONLY.  The load-bearing activation
 * evidence is the kernel's own `Seccomp:`/`Seccomp_filters:` in
 * /proc/<pid>/status, read by the inspector from OUTSIDE while this process is
 * blocked at the barrier.  A harness boolean and a self-report can both lie or
 * be mis-targeted; the external kernel read is the one that counts.
 */
static int d3_confirm_policy_in_process(void) {
    return prctl(PR_GET_SECCOMP, 0, 0, 0, 0);
}

