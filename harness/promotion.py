def _lock_shas(fam_c_dir):
    out = {}
    for key, name in (("protocol_lock_sha256", "PROTOCOL-LOCK.json"),
                      ("execution_lock_sha256", "EXECUTION-LOCK.json")):
        p = os.path.join(fam_c_dir, name)
        if not os.path.isfile(p):
            raise PermissionError(f"PROMOTION-DENY frozen {name} absent")
        out[key] = _sha_file(p)
    return out


def promote_universe(fam_c_dir, block, family, universe, freeze_commit=None,
                     evidence_grade="estimand", version="1.0.0",
                     builder_identity=None):
    """Run the PROMOTION event for one universe. Refuses unless PROMOTION is
    the derived next authorized event."""
    event, cell, reasons = next_event(fam_c_dir, block, family, universe,
                                      freeze_commit)
    if reasons:
        raise PermissionError(reasons[0])
    if event != "PROMOTION":
        raise PermissionError(
            f"PROMOTION-DENY {block}/{family}/{universe} next authorized "
            f"event is {event}, not PROMOTION (the controller derives the "
            f"event; operators never choose one)")
    reasons = _authorized_cell(fam_c_dir, cell, freeze_commit)
    if reasons:
        raise PermissionError(reasons[0])
    if evidence_grade not in GRADES:
        raise ValueError(f"PROMOTION-DENY evidence_grade {evidence_grade!r} "
                         f"not in {list(GRADES)}")
    exp = order.load_expansion(fam_c_dir)
    t0 = order.expected_event(exp, block, family, "T0", universe)
    t1 = order.expected_event(exp, block, family, "T1", universe)
    if t0 is None or t1 is None:
        raise PermissionError("PROMOTION-DENY order has no T0/T1 pair for "
                              f"{block}/{family}/{universe}")
    if evidence_grade == "estimand" and builder_identity is not None:
        raise PermissionError(
            "PROMOTION-DENY estimand promotion derives producer identity "
            "exclusively from the validated T0/T1 identity records (no "
            "operator-supplied builder_identity)")
    # A12d D1-B3: a T1 whose candidate validation FAILED still completed
    # its cell — the failed acquisition is a RECORDED terminal outcome,
    # not a deadlock: the controller records PROMOTION-OUTCOME.json and
    # then REFUSES with a clean PROMOTION-DENY (never a lock). Anything
    # else (no event, several events, an unreadable chain, an event that
    # does not bind the frozen candidate) falls through to the normal
    # path, which denies as before.
    _failed, _cause = order.acquisition_failed(fam_c_dir, block, family,
                                               universe)
    if _failed:
        _t1_dir = order.run_dir(fam_c_dir, t1)
        _t0_dir = order.run_dir(fam_c_dir, t0)
        try:
            _t0_arr = _read_json(os.path.join(_t0_dir, "arrival.json"))
            _t0_src = (_t0_arr.get("execution_payload") or {}).get(
                "solver_py")
            _frozen = (_sha_bytes(_t0_src.encode())
                       if isinstance(_t0_src, str) and _t0_src.strip()
                       else None)
        except (ValueError, OSError):
            _frozen = None
        if _frozen is None:
            raise PermissionError(
                "PROMOTION-DENY T0 arrival carries no frozen candidate "
                "(failed-acquisition outcome not recordable)")
        _cap = order.capability_dir(fam_c_dir, block, universe, family)
        if os.path.exists(os.path.join(_cap, "CAPABILITY_LOCK.json")):
            raise PermissionError(
                "PROMOTION-DENY universe "
                f"{block}/{family}/{universe} has a CAPABILITY_LOCK but "
                f"its T1 candidate validation failed ({_cause}; no lock "
                f"may exist for a failed acquisition)")
        _t0_tip = order._chain_tip(os.path.join(_t0_dir,
                                                "EVIDENCE-CHAIN.jsonl"))
        _t1_tip = order._chain_tip(os.path.join(_t1_dir,
                                                "EVIDENCE-CHAIN.jsonl"))
        _op = order.emit_promotion_outcome(fam_c_dir, cell, _t0_tip,
                                           _t1_tip, _frozen)
        raise PermissionError(
            f"PROMOTION-DENY universe {block}/{family}/{universe} T1 "
            f"candidate validation failed ({_cause}): promotion is "
            f"NOT-PROMOTED (terminal outcome recorded at {_op}), no "
            f"CAPABILITY_LOCK may exist for it, and every downstream "
            f"cell of that universe is NOT-EVALUABLE (no retry: the "
            f"failed validation is an experimental outcome)")
    t0_ev = run_evidence(fam_c_dir, t0, freeze_commit)
    t1_ev = run_evidence(fam_c_dir, t1, freeze_commit)
    producer_identity = _producer_identity(t0_ev, t1_ev)
    cand = derive_candidate(t0_ev, t1_ev, t0_ev["run_dir"])
    # A12b.1/AC6b: the promoted contract is authored by the PRODUCER — it
    # is read from the T0 arrival's own `capability_contract` declaration,
    # never synthesized from hidden K.md (which nothing in the promotion
    # path reads).
    contract = _producer_contract(t0_ev["run_dir"])
    core_sha = _sha_bytes(contract[0].encode())
    t4_id, t4_ratified = t4_semantic_id(fam_c_dir, cell["family"],
                                        core_sha, evidence_grade)
    # A12c slice C2 (auditor P0 #6), A12d slice D5 (auditor D4-post
    # P0): the frozen structural requires_all->T4-id conformance
    # bridge. The lock records the producer's ACTUAL contract plus the
    # derived verdict — derived HERE mechanically from the
    # producer-declared contract through the SINGLE governed
    # implementation (harness/conformance.py over the frozen
    # T4-CONFORMANCE.json map, never by copying hidden K.md text: this
    # controller has no hidden-contract reader by design, and the
    # conformance check reads the lock only). Conformance consults ONLY
    # the structural preconditions[*].requires_all token lists: an
    # unrelated token list (e.g. ['python', '3']) — and every
    # limitation, always — leaves the T4 non-discriminating, because
    # only a requires_all list naming the T4's applicability condition
    # (a frozen predicate match over an admissible atomic token list)
    # supports the id.
    declared_limitations_present = bool(contract[2])
    cmap = _conformance.load(fam_c_dir)
    # A12d slice D6 (auditor D5-post P0): NO vocabulary gate — the
    # contract above already survived structural validation (arbitrary
    # atomic tokens preserved verbatim). The auditor-side recognition
    # set is consulted ONLY inside conformance.verdict() below, which
    # marks unknown-atom preconditions non-conformance-bearing; it
    # never denies promotion. This controller does not read the
    # recognition set at all.
    cverdict = _conformance.verdict(
        cell["family"],
        [p["requires_all"] for p in contract[1]], cmap,
        limitations=contract[2])
    non_discriminating = cverdict["non_discriminating"]
    conformance_cause = cverdict["conformance_cause"]
    supported_t4_ids = cverdict["supported_t4_ids"]
    conformance_map_sha256 = cverdict["conformance_map_sha256"]
    shas = _lock_shas(fam_c_dir)
    capdir = order.ensure_namespace(fam_c_dir, block, universe, family,
                                    tail=("capability",))
    cell = dict(cell)
    cell["source_cells"] = {"T0": t0_ev["cell_id"], "T1": t1_ev["cell_id"]}
    cell["acquisition_chain_tips"] = {"T0": t0_ev["chain_tip"],
                                      "T1": t1_ev["chain_tip"]}
    if cell["source_cells"]["T0"] == cell["source_cells"]["T1"]:
        raise PermissionError("PROMOTION-DENY identical source cells")
    arts = _mint_artifacts(capdir, cand, contract, cell,
                           shas["protocol_lock_sha256"],
                           shas["execution_lock_sha256"], version,
                           evidence_grade, t4_id, t4_ratified)
    exp_sha = _sha_file(os.path.join(fam_c_dir, "ORDER-EXPANSION.json"))
    done = order.completed_cells(fam_c_dir, freeze_commit, exp)
    provenance = {
        "version": version,
        "acquisition_chain_tips": dict(cell["acquisition_chain_tips"]),
        "source_cells": dict(cell["source_cells"]),
        "candidate": {k: cand[k] for k in ("sha256", "field",
                                           "arrival_sha256", "payload_sha256",
                                           "t1_used_candidate", "t1_decision",
                                           "t1_validation")},
        "artifacts": arts,
        "semantic_core": contract[0],
        "semantic_core_sha256": core_sha,
        "preconditions": contract[1], "limitations": contract[2],
        "declared_limitations_present": declared_limitations_present,
        "non_discriminating": non_discriminating,
        "conformance_cause": conformance_cause,
        "supported_t4_ids": supported_t4_ids,
        "conformance_map_sha256": conformance_map_sha256,
        "t4_semantic_id": t4_id, "t4_ratified": t4_ratified,
        "evidence_grade": evidence_grade,
        "producer_identity": producer_identity,
        "protocol_lock_sha256": shas["protocol_lock_sha256"],
        "execution_lock_sha256": shas["execution_lock_sha256"],
        "authorization": {
            "order_sha256": exp_sha, "event_index": cell["index"],
            "done_cells_at_emit": sorted(done),
            "event": "PROMOTION"},
        "t0_evidence": _per_cell_evidence(t0_ev),
        "t1_evidence": _per_cell_evidence(t1_ev),
    }
    rp = order.emit_promotion_receipt(fam_c_dir, cell,
                                      cell["acquisition_chain_tips"]["T0"],
                                      cell["acquisition_chain_tips"]["T1"],
                                      builder_identity=provenance[
                                          "producer_identity"],
                                      provenance=provenance)
    return {"event": "PROMOTION", "cell_id": cell["cell_id"],
            "receipt": rp, "receipt_sha256": _sha_file(rp),
            "capability_dir": capdir, "artifacts": arts,
            "candidate_sha256": cand["sha256"],
            "t4_semantic_id": t4_id, "t4_ratified": t4_ratified,
            "evidence_grade": evidence_grade}


def lock_universe(fam_c_dir, block, family, universe, freeze_commit=None,
                  evidence_grade=None, builder_identity=None):
    """Run the CAPABILITY_LOCK event for one universe. The lock may only
    name the artifact hashes recorded in the validated PROMOTION receipt."""
    event, cell, reasons = next_event(fam_c_dir, block, family, universe,
                                      freeze_commit)
    if reasons:
        raise PermissionError(reasons[0])
    if event != "CAPABILITY_LOCK":
        raise PermissionError(
            f"LOCK-DENY {block}/{family}/{universe} next authorized event is "
            f"{event}, not CAPABILITY_LOCK")
    reasons = _authorized_cell(fam_c_dir, cell, freeze_commit)
    if reasons:
        raise PermissionError(reasons[0])
    exp = order.load_expansion(fam_c_dir)
    prom = order.expected_event(exp, block, family, "PROMOTION", universe)
    if prom is None:
        raise PermissionError("LOCK-DENY order has no PROMOTION cell")
    pst = order.cell_state(fam_c_dir, prom, freeze_commit)
    if pst["status"] != "COMPLETE":
        raise PermissionError("LOCK-DENY PROMOTION not COMPLETE "
                              f"({pst['status']}: {pst['reasons'][:1]})")
    rp = os.path.join(order.run_dir(fam_c_dir, prom), "PROMOTION-RECEIPT.json")
    rec = _read_json(rp)
    arts = rec.get("artifacts")
    if not isinstance(arts, dict) or not arts:
        raise PermissionError("LOCK-DENY promotion receipt names no artifacts "
                              "(lock may only lock receipt-named hashes)")
    capdir = order.capability_dir(fam_c_dir, block, universe, family)
    paths = []
    for name, want in sorted(arts.items()):
        if os.path.basename(name) != name:
            raise PermissionError(f"LOCK-DENY artifact name {name!r} is not a "
                                  f"bare filename")
        p = os.path.join(capdir, name)
        if not os.path.isfile(p) or os.path.islink(p):
            raise PermissionError(f"LOCK-DENY receipt names {name} but it is "
                                  f"absent from {capdir}")
        got = _sha_file(p)
        if got != want:
            raise PermissionError(f"LOCK-DENY receipt artifact {name} hash "
                                  f"{want[:12]} != present {got[:12]}")
        paths.append(p)
    lp = order.emit_capability_lock(fam_c_dir, cell, artifact_paths=paths,
                                    version=rec.get("version", "1.0.0"),
                                    manifest_obj=rec.get("manifest_obj") or {
                                        "capability_id": cell["capability_id"],
                                        "candidate_sha256":
                                            rec["candidate"]["sha256"],
                                        "source_cells": rec["source_cells"],
                                        "semantic_core_sha256":
                                            rec["semantic_core_sha256"],
                                        "artifacts": arts},
                                    training_receipts=[rec["source_cells"]["T0"],
                                                       rec["source_cells"]["T1"]],
                                    builder_identity=rec.get(
                                        "producer_identity") or {},
                                    receipt=rec, receipt_path=rp)
    return {"event": "CAPABILITY_LOCK", "cell_id": cell["cell_id"],
            "lock": lp, "lock_sha256": _sha_file(lp), "artifacts": arts,
            "capability_dir": capdir}


def advance(fam_c_dir, block, family, universe, freeze_commit=None,
            evidence_grade="estimand", version="1.0.0",
            builder_identity=None):
    """Derive the next authorized acquisition event for this universe and
    execute it if it is a governance event. T0/T1 are refused here: they are
    model calls and belong to the acquisition executor (A12.0-d)."""
    event, cell, reasons = next_event(fam_c_dir, block, family, universe,
                                      freeze_commit)
    if reasons:
        raise PermissionError(reasons[0])
    if event == "PROMOTION":
        return promote_universe(fam_c_dir, block, family, universe,
                                freeze_commit, evidence_grade, version,
                                builder_identity)
    if event == "CAPABILITY_LOCK":
        return lock_universe(fam_c_dir, block, family, universe,
                             freeze_commit, evidence_grade, builder_identity)
    raise PermissionError(
        f"ACQUISITION-REQUIRED: {block}/{family}/{universe} next authorized "
        f"event is {event} ({cell['cell_id']}); run it through the "
        f"acquisition executor, not the governance controller")


