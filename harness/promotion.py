    ap.add_argument("--family", required=True)
    ap.add_argument("--universe", required=True)
    ap.add_argument("--freeze-commit")
    ap.add_argument("--evidence-grade", default="estimand", choices=GRADES)
    ap.add_argument("--version", default="1.0.0")
    a = ap.parse_args(argv)
    try:
        out = advance(a.fam_c_dir, a.block, a.family, a.universe,
                      a.freeze_commit, a.evidence_grade, a.version)
    except (PermissionError, ValueError) as e:
        print(f"CONTROLLER-REFUSED: {e}")
        return 2
    print(json.dumps(out, indent=1, sort_keys=True))
    return 0


