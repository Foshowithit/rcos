def _producer_identity(t0_ev, t1_ev):
    """Derive the promotion receipt's producer identity EXCLUSIVELY from
    the validated T0/T1 identity records: requested model, echoed model,
    provider response id, identity sha, lane, and source cell per
    acquisition event. No operator-supplied builder_identity."""
    out = {"producer": "harness/promotion.py"}
    for tag, ev in (("t0", t0_ev), ("t1", t1_ev)):
        ident = ev["identity"]
        out[tag] = {
            "source_cell": ident["source_cell"], "lane": ident["lane"],
            "endpoint": ident["endpoint"],
            "model_requested": ident["model_requested"],
            "model_echoed": ident["model_echoed"],
            "provider_response_id": ident["provider_response_id"],
            "identity_sha256": ident["identity_sha256"],
            "identity_prereg_family": ident["identity_prereg_family"]}
        out[tag + "_lane"] = ev["lane"]
        out[tag + "_verdict"] = ev["verdict"]
    return out


def _t1_candidate_validation(t1_run_dir, t0_sha):
    """Re-derive the T1 candidate-validation evidence from the committed
    T1 chain (fail closed). A12c D3 + A12d D1-C3: promotion requires
    exactly one candidate-validation event with all eleven fields
    present/non-null, `validated is True`, `validation_verdict == "ship"`,
    `candidate_sha256 == executed_sha256 == T0 arrival candidate sha`,
    and a 64-hex `adapter_sha256` (plus 64-hex candidate-output / checker
    / truth shas and checker_returncode == 0 — the host-side T1 checker
    over CANDIDATE-OUTPUT.json), plus the two input-lineage hashes
    re-derived from the COMMITTED artifacts: the persisted
    CANDIDATE-INPUT-MANIFEST.json file bytes must hash to
    `candidate_input_manifest_sha256` and the manifest's recomputed tree
    hash must equal `candidate_input_tree_sha256` (never trusted from the
    receipt), and the event's `candidate_sha256` must equal the frozen T0
    candidate. Any deviation -> PROMOTION-DENY naming the exact
    missing/mismatched field. The chain must carry EXACTLY ONE such event
    binding the SAME frozen T0 candidate: a T1 with no such event — a
    standalone fresh solve that never saw the candidate — can NEVER
    promote; a T1 whose single event records validated=false promotes as
    a RECORDED NOT-PROMOTED outcome (see promote_universe), never a lock.
    """
    links = _read_chain_links(t1_run_dir)
    evs = [l for l in links if l.get("kind") == "candidate-validation"]
    if len(evs) != 1:
        raise PermissionError(
            f"PROMOTION-DENY T1 chain carries {len(evs)} "
            f"candidate-validation events, need exactly one (a T1 with "
            f"no candidate-validation event never validated the frozen "
            f"candidate and can never promote)")
    pay = evs[-1].get("payload") or {}
    for f in ("candidate_sha256", "executed_sha256", "adapter_sha256",
              "candidate_output_sha256", "checker_sha256", "truth_sha256",
              "checker_returncode", "validation_verdict", "validated",
              "candidate_input_manifest_sha256",
              "candidate_input_tree_sha256"):
        if pay.get(f) is None:
            raise PermissionError(
                f"PROMOTION-DENY T1 candidate-validation event carries "
                f"no {f} (got {pay.get(f)!r}; all eleven keys must be "
                f"present and non-null)")
    for f in ("candidate_sha256", "executed_sha256", "adapter_sha256",
              "candidate_output_sha256", "checker_sha256", "truth_sha256",
              "candidate_input_manifest_sha256",
              "candidate_input_tree_sha256"):
        v = pay.get(f)
        if not (isinstance(v, str) and len(v) == 64):
            raise PermissionError(
                f"PROMOTION-DENY T1 candidate-validation event carries "
                f"no 64-hex {f} (got {v!r})")
        try:
            int(v, 16)
        except ValueError:
            raise PermissionError(
                f"PROMOTION-DENY T1 candidate-validation event carries "
                f"no 64-hex {f} (got {v!r})") from None
    if pay.get("candidate_sha256") != t0_sha:
        raise PermissionError(
            f"PROMOTION-DENY T1 validated candidate "
            f"{pay['candidate_sha256'][:12]} != the frozen T0 candidate "
            f"{t0_sha[:12]} (independent validation must test the SAME "
            f"frozen candidate)")
    if pay.get("executed_sha256") != t0_sha:
        raise PermissionError(
            f"PROMOTION-DENY T1 adapter executed "
            f"{pay['executed_sha256'][:12]} != the frozen T0 candidate "
            f"{t0_sha[:12]} (validation means executing the SAME "
            f"candidate bytes)")
    if pay.get("checker_returncode") != 0:
        raise PermissionError(
            f"PROMOTION-DENY T1 candidate-validation checker_returncode "
            f"{pay.get('checker_returncode')!r} != 0 (the host-side T1 "
            f"checker must pass over CANDIDATE-OUTPUT.json)")
    if pay.get("validation_verdict") != "ship":
        raise PermissionError(
            f"PROMOTION-DENY T1 candidate-validation validation_verdict "
            f"{pay.get('validation_verdict')!r} != 'ship' (the host-side "
            f"T1 checker must pass over CANDIDATE-OUTPUT.json)")
    if pay.get("validated") is not True:
        raise PermissionError(
            f"PROMOTION-DENY T1 candidate-validation event is not "
            f"validated (validated={pay.get('validated')!r})")
    # A12d D1-C3: the input lineage is re-derived from the COMMITTED
    # artifacts (the persisted manifest file + this event), never from the
    # receipt. Any mismatch denies naming the field.
    for _lr in order.candidate_input_lineage_reasons(t1_run_dir, pay):
        raise PermissionError(f"PROMOTION-DENY T1 {_lr}")
    return {"candidate_sha256": pay["candidate_sha256"],
            "executed_sha256": pay["executed_sha256"],
            "adapter_sha256": pay["adapter_sha256"],
            "candidate_output_sha256": pay["candidate_output_sha256"],
            "checker_sha256": pay["checker_sha256"],
            "truth_sha256": pay["truth_sha256"],
            "checker_returncode": pay["checker_returncode"],
            "validation_verdict": pay["validation_verdict"],
            "validated": True,
            "candidate_input_manifest_sha256": pay[
                "candidate_input_manifest_sha256"],
            "candidate_input_tree_sha256": pay[
                "candidate_input_tree_sha256"]}


def derive_candidate(t0_ev, t1_ev, t0_run_dir):
    """The candidate is the T0 arrival's `solver_py` payload, content-
    addressed. T1 must have VALIDATED it: the T1 chain carries exactly one
    candidate-validation event for this same candidate (fail closed — the
    no-declaration path is DELETED; a standalone fresh T1 may still SHIP
    its own cell, but it can never promote). If T1 declares a candidate
    hash in its arrival it must match exactly."""
    ap = os.path.join(t0_run_dir, "arrival.json")
    arrival = _read_json(ap)
    payload = _arrival_payload(arrival)
    src = payload.get("solver_py")
    if not isinstance(src, str) or not src.strip():
        raise PermissionError("PROMOTION-DENY T0 arrival carries no "
                              "execution_payload.solver_py candidate")
    if arrival.get("decision") != "fresh":
        raise PermissionError("PROMOTION-DENY T0 decision "
                              f"{arrival.get('decision')!r} != 'fresh' "
                              "(acquisition must solve fresh)")
    sha = _sha_bytes(src.encode())
    # A12b.2: the fail-closed validation gate — the T1 chain must prove
    # the adapter saw and executed THIS frozen candidate. No event, no
    # promotion (a standalone fresh T1 still SHIPs its cell; SHIP is not
    # promotion).
    t1_dir = t1_ev["run_dir"]
    t1_validation = _t1_candidate_validation(t1_dir, sha)
    declared = None
    t1_arr = _read_json(os.path.join(t1_dir, "arrival.json"))
    t1_payload = _arrival_payload(t1_arr)
    if isinstance(t1_payload.get("candidate_sha256"), str):
        declared = t1_payload["candidate_sha256"]
    if t1_arr.get("decision") == "use_capability":
        if declared is None:
            raise PermissionError("PROMOTION-DENY T1 chose use_capability but "
                                  "declares no candidate_sha256")
        if declared != sha:
            raise PermissionError(
                f"PROMOTION-DENY T1 used candidate {declared[:12]} but T0 "
                f"candidate is {sha[:12]} (independent validation must test "
                f"the SAME frozen candidate)")
    elif declared is not None and declared != sha:
        raise PermissionError("PROMOTION-DENY T1 declares a different "
                              f"candidate {declared[:12]} != T0 {sha[:12]}")
    if t1_ev["task"] == t0_ev["task"]:
        raise PermissionError("PROMOTION-DENY T0 and T1 share one task id; "
                              "promotion requires a distinct task/surface")
    if (t0_ev["task_snapshot_hash"]
            and t0_ev["task_snapshot_hash"] == t1_ev["task_snapshot_hash"]):
        raise PermissionError("PROMOTION-DENY T0 and T1 have identical task "
                              "snapshots; promotion requires a distinct "
                              "task/surface")
    return {"sha256": sha, "source": src, "field": CANDIDATE_FIELD,
            "arrival_sha256": t0_ev["arrival_sha256"],
            "payload_sha256": _sha_bytes(_canon(payload).encode()),
            "t1_used_candidate": t1_arr.get("decision") == "use_capability",
            "t1_decision": t1_arr.get("decision"),
            "t1_validation": t1_validation}


